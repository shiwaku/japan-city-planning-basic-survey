/**
 * 表示テーマの定義。色は palettes.ts が用途区分ごとに持つ。
 *
 * ## 収録を土地利用と建物に絞っている
 *
 * 都市計画基礎調査は法定 17 項目あり、収集と変換は 10 項目ぶん続けているが、
 * 配信タイルに載せるのはこの 2 つだけにした。外した 8 項目（人口・産業・
 * 都市施設・地価・自然環境・災害・景観・その他）は、どれも国が全国整備している
 * 一次データの劣化版になっていたため。
 *
 *   人口・産業は 250m/500m メッシュと小地域の集計値で、同じ集計が e-Stat の
 *   統計 GIS に全国・全年次ぶんある。地価・災害・景観・都市施設・区域界は
 *   国土数値情報に全国・毎年更新のものがある。
 *
 * こちらは自治体ごとに虫食いで、年次もばらばらで、正規化もしていない。
 * 対して土地利用と建物には国の全国整備がなく、自治体のオープンデータを横断して
 * 国標準コードに正規化したこのタイル自体に意味がある。
 * 除外の実装は `cli.py` の PUBLISHED_THEMES。
 *
 * ## 単色スロットをやめた
 *
 * 以前は 10 テーマを重ねる前提で、検証済みカテゴリカル配色から 3 スロットを
 * 割り当て、同時表示も 3 テーマまでに制限していた。残った 2 つはどちらも
 * 用途区分ごとの塗り分け（20 区分・19 区分）を持つので、テーマを代表する
 * 単色そのものが描画に使われない。パネルの色見本も、実際の塗りと合わないまま
 * 出ていたので落とした。識別は凡例の区分名が担う。
 */

export interface ThemeDef {
  /** PMTiles のファイル名・source-layer 名と一致する。 */
  key: string
  /** 表示名 */
  name: string
  /** 初期表示 ON/OFF */
  on: boolean
  /** パネルに出す説明 */
  desc: string
}

/** 収録テーマ。並び順はパネルの上から順。 */
export const THEMES: ThemeDef[] = [
  {
    key: 'landuse', name: '土地利用', on: true,
    desc: '土地利用現況。敷地単位のポリゴンに用途を持つものだけを収録し、国標準の用途コードで塗り分けている。小地域集計・開発許可の点などは別物なので入れていない。',
  },
  {
    key: 'building', name: '建物', on: true,
    desc: '建物利用現況。1棟ごとのポリゴンに用途を持つものだけを収録し、国標準の建物用途コードで塗り分けている。実測の高さがある棟は、地図を傾けると立体で表示される。',
  },
]

export const themeOf = (key: string): ThemeDef | undefined =>
  THEMES.find((t) => t.key === key)

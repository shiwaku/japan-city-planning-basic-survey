/** 属性名の表記ゆれを吸収する（埼玉県の DBF は名前に \r が入る）。 */
export function labelOf(name: string): { label: string; raw: string | null } {
  const key = name.replace(/[\r\n\t]/g, '').trim()
  const label = FIELD_NAMES[key]
  return label ? { label, raw: key } : { label: key, raw: null }
}
